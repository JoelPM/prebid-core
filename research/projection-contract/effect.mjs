// Which projection differences change a real Adapter's output? Runs the prototype's OpenX and PubMatic
// Definitions (TS as written, server side, via prototype/abi core's build().makeBids) on the exact
// reading of each response case and on what each Host model hands over, and compares the outputs as
// JSON values (ADR 0001: key order free, undefined members dropped).
//
// Only what the Adapter itself emits is compared: type, seat, dealPriority, video, meta, errors,
// currency, paapi, and the bid fields it overrides (PubMatic's cat and adm). The rest of each bid comes
// from the Host's own parsed bid, not from the projection.
//
// Usage: node effect.mjs [path to prototype/abi]   (after run.sh; writes results/effect.md)
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url).pathname;
const abi = process.argv[2] ?? here + '../../../prebid-core-wt-abi/prototype/abi';
const { build } = await import(abi + '/core/index.ts');
const adapters = {
  openx: build((await import(abi + '/adapters/openx.ts')).default, 'server'),
  pubmatic: build((await import(abi + '/adapters/pubmatic.ts')).default, 'server'),
};
// The outgoing request MakeBids sees (its own MakeRequests output): one banner imp "1".
const breq = { imp: [{ id: '1', banner: { w: 300, h: 250 } }] };

const canon = (v) => JSON.stringify(v, (k, x) => (x && typeof x === 'object' && !Array.isArray(x)
  ? Object.fromEntries(Object.keys(x).sort().filter((y) => x[y] !== undefined).map((y) => [y, x[y]])) : x));
function run(a, resp) {
  try {
    const r = adapters[a].makeBids(breq, resp);
    // overrides: the fields of r.bid that differ from the bid it was built from
    let i = 0; const inBids = (resp?.seatbid ?? []).flatMap((sb) => sb?.bid ?? []);
    const bids = r.bids.map((b) => {
      const src = inBids[i++] ?? {};
      const ov = Object.fromEntries(Object.keys(b.bid ?? {}).filter((k) => canon(b.bid[k]) !== canon(src[k])).map((k) => [k, b.bid[k]]));
      return { type: b.type, seat: b.seat, dealPriority: b.dealPriority, video: b.video, meta: b.meta, ov };
    });
    return canon({ bids, currency: r.currency, paapi: r.paapi, errs: r.errs });
  } catch (e) {
    return 'throws: ' + e.message;
  }
}

// compare.mjs's `normalize`, on JS values: optional typed members (outside `ext`) that are null, 0, ""
// or [] are dropped and required ones (bid.impid, seatbid.bid) default to their zero, before the
// Phases run, as the proposed contract has Prebid Core do on every Host.
const REQUIRED = { '.seatbid[]': { bid: [] }, '.seatbid[].bid[]': { impid: '' } };
function normalize(v, inExt = false, at = '') {
  if (Array.isArray(v)) return v.map((x) => normalize(x, inExt, at + '[]'));
  if (v === null || typeof v !== 'object') return v;
  const req = inExt ? {} : REQUIRED[at] ?? {};
  const o = {};
  for (const [k, c] of Object.entries(v)) {
    if (!inExt && (c === null || c === 0 || c === '' || (Array.isArray(c) && !c.length))) {
      if (k in req) o[k] = c === null ? req[k] : c;
      continue;
    }
    o[k] = normalize(c, inExt || k === 'ext', at + '.' + k);
  }
  for (const k of Object.keys(req)) if (!(k in o)) o[k] = req[k];
  return o;
}

const b64 = (s) => Buffer.from(s, 'base64');
const load = (f) => new Map(readFileSync(here + f, 'utf8').trim().split('\n').map(JSON.parse).filter((l) => l.kind === 'resp').map((l) => [l.case, l]));
const go = load('out-go.jsonl'), java = load('out-java.jsonl'), rust = load('out-rust.jsonl');
const parse = (b) => JSON.parse(new TextDecoder().decode(b));
const HOSTS = [
  ['PBS-Go struct', (c) => (go.get(c).err ? null : parse(b64(go.get(c).struct)))],
  ['PBS-Go raw', (c) => parse(b64(go.get(c).raw))],
  ['PBS-Go shadow', (c) => (go.get(c).shadowErr ? null : parse(b64(go.get(c).shadow)))],
  ['PBS-Java ext as ObjectNode', (c) => (java.get(c).objextErr ? null : parse(b64(java.get(c).objext)))],
  ['Trusted Server typed', (c) => (rust.get(c).typedErr ? null : parse(b64(rust.get(c).typed)))],
  ['Trusted Server Value', (c) => (rust.get(c).valueErr ? null : parse(b64(rust.get(c).value)))],
];

let md = '# Does the difference change OpenX or PubMatic output?\n\nGenerated by `effect.mjs`. Reference: the Definition run on `JSON.parse` of the case bytes. `=` same output, `≠` different output, `✗` the Host rejects the response (no bids at all), `·` same as reference because the Host model handed over the same input.\n\n';
md += `| case | ${HOSTS.map((h) => h[0]).flatMap((h) => [h + ' OpenX', 'PubMatic']).join(' | ')} |\n|---|${HOSTS.flatMap(() => [':-:', ':-:']).join('|')}|\n`;
let details = '', ndetails = '';
const counts = {};
for (const c of [...go.keys()].sort()) {
  const ref = parse(readFileSync(`${here}cases/resp/${c}.json`));
  const row = [];
  let interesting = false;
  for (const [name, get] of HOSTS) {
    const v = get(c);
    for (const a of ['openx', 'pubmatic']) {
      const key = `${name} ${a}`; counts[key] ??= { same: 0, diff: 0, rej: 0, ndiff: 0 };
      if (v === null) { row.push('✗'); counts[key].rej++; interesting = true; continue; }
      const x = run(a, ref), y = run(a, v);
      const nx = run(a, normalize(ref)), ny = run(a, normalize(v));
      if (nx !== ny) { counts[key].ndiff++; ndetails += `- **${c}**, ${name}, ${a}:\n  - exact: \`${nx}\`\n  - Host:  \`${ny}\`\n`; }
      if (x === y) { row.push(canon(v) === canon(ref) ? '·' : '='); counts[key].same++; continue; }
      row.push('≠'); counts[key].diff++; interesting = true;
      details += `- **${c}**, ${name}, ${a}:\n  - exact: \`${x}\`\n  - Host:  \`${y}\`\n`;
    }
  }
  if (interesting) md += `| ${c} | ${row.join(' | ')} |\n`;
}
md += '\nRows where every Host gives the same output are omitted.\n\n## Totals (all response cases)\n\n`different once normalized`: both inputs normalized (null/zero typed members dropped) before the Phases run.\n\n| Host model, Adapter | same output | different | rejected | different once normalized |\n|---|--:|--:|--:|--:|\n';
for (const [k, t] of Object.entries(counts)) md += `| ${k} | ${t.same} | ${t.diff} | ${t.rej} | ${t.ndiff} |\n`;
md += '\n## Output differences\n\n' + details + '\n## Output differences once normalized\n\n' + ndetails;
writeFileSync(here + 'results/effect.md', md);
