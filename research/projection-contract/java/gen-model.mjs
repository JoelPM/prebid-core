// Mirrors PBS-Java's OpenRTB model (com.iab.openrtb.*, Lombok @Value classes) as Java records with the
// same field names, types and @JsonProperty/@JsonIgnore annotations, so Jackson decodes them as PBS-Java
// does. Lombok can't run on the only JDK here (27); a record's canonical constructor is the same
// properties-based creator Lombok's @ConstructorProperties constructor gives Jackson.
// Types outside com.iab.openrtb (PBS's typed ext classes such as ExtRequest) become JsonNode: an
// approximation noted in the findings; no path the prototype Adapters read goes through one, except
// response.ext (ExtBidResponse), which is mirrored by hand below.
// Usage: node gen-model.mjs <prebid-server-java>/src/main/java > Model.java
import { readFileSync, existsSync } from 'node:fs';

const root = process.argv[2] + '/com/iab/openrtb/';
const KEEP = new Set(['String', 'Integer', 'Long', 'Double', 'Float', 'Boolean', 'BigDecimal', 'ObjectNode', 'JsonNode', 'List', 'Map']);
const done = new Map();
const queue = [['response', 'BidResponse'], ['request', 'BidRequest']];

function file(name) {
  for (const pkg of ['response', 'request']) if (existsSync(`${root}${pkg}/${name}.java`)) return `${root}${pkg}/${name}.java`;
  return null;
}
function mapType(t) {
  return t.replace(/\b[A-Z][A-Za-z0-9]*\b/g, (n) => {
    if (KEEP.has(n)) return n;
    if (n === 'ExtBidResponse') return 'ExtBidResponse';
    if (file(n)) { if (!done.has(n)) queue.push([null, n]); return n; }
    return 'JsonNode';
  });
}
while (queue.length) {
  const [, name] = queue.shift();
  if (done.has(name)) continue;
  const src = readFileSync(file(name), 'utf8');
  const body = src.slice(src.indexOf(`class ${name}`));
  const fields = [];
  let ann = [];
  for (const line of body.split('\n')) {
    const a = line.match(/^    (@Json\w+(\(.*\))?)\s*$/);
    if (a) { ann.push(a[1]); continue; }
    if (/^    @/.test(line)) continue; // other annotations (Lombok @Getter) keep the pending ones
    const f = line.match(/^    ([A-Z][\w<>, ]*?) (\w+);/);
    if (f) { fields.push(`${ann.join(' ')} ${mapType(f[1])} ${f[2]}`.trim()); ann = []; continue; }
    if (/^    \S/.test(line) && !line.trim().startsWith('*') && !line.trim().startsWith('/')) ann = [];
  }
  done.set(name, `    public record ${name}(\n        ${fields.join(',\n        ')}) {}\n`);
}

console.log(`// GENERATED by gen-model.mjs from PBS-Java's com.iab.openrtb model. Do not edit.
import com.fasterxml.jackson.annotation.*;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.math.BigDecimal;
import java.util.List;
import java.util.Map;

public final class Model {
    // org.prebid.server.proto.openrtb.ext.response.ExtBidResponse: its fields, typed ones as JsonNode.
    // It has no fledge_auction_configs member, so Jackson drops it (FAIL_ON_UNKNOWN_PROPERTIES off).
    public record ExtBidResponse(JsonNode debug, JsonNode seatnonbid, JsonNode errors, JsonNode warnings,
        JsonNode responsetimemillis, Long tmaxrequest, JsonNode usersync, JsonNode prebid) {}
    // What a Shared Adapter Host binding would decode instead: the same response with ext kept whole.
    public record BidResponseObjectExt(String id, List<SeatBid> seatbid, String bidid, String cur,
        String customdata, Integer nbr, ObjectNode ext) {}
${[...done.values()].join('')}}`);
